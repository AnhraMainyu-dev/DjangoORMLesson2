@user_passes_test(is_manager, login_url="restaurateur:login")
def view_orders(request):
    orders = list(
        Order.objects.with_sum()
        .exclude(status__in=Order.FINISHED_STATUSES)
        .with_status_order()
        .prefetch_related("items")
        .select_related("restaurant")
    )

    menu_by_restaurant = RestaurantMenuItem.objects.make_menu_by_restaurant()
    restaurants = Restaurant.objects.in_bulk()

    for order in orders:
        order.available_restaurants = find_suited_restaurants(
            order, menu_by_restaurant, restaurants
        )

    addresses = {order.address for order in orders}
    addresses.update(
        restaurant.address
        for order in orders
        for restaurant in order.available_restaurants
    )

    coordinates_by_address = Address.objects.get_coordinates(addresses)

    for order in orders:
        order.restaurants_with_distance = measure_distances(
            order.available_restaurants,
            coordinates_by_address[order.address],
            coordinates_by_address,
        )

    return render(request, template_name="order_items.html", context={"orders": orders})
